"""Prototype d'isolation du catalogue UUID et du schéma historique integer.

Toutes les vérifications utilisent un PostgreSQL jetable. Aucun accès réseau Supabase.
"""
from __future__ import annotations

import pathlib
import tempfile

import pytest


def _connexion_jetable():
    try:
        import pgserver  # type: ignore
        import psycopg  # type: ignore
    except ImportError as exc:
        pytest.fail(
            "Les tests d’isolation exigent pgserver et psycopg ; "
            "un test sauté ne constitue pas une validation.",
            pytrace=False,
        )
    serveur = pgserver.get_server(tempfile.mkdtemp(prefix="dekk-isolation-test-"))
    return psycopg.connect(serveur.get_uri(), autocommit=True)


def test_catalogue_uuid_coexiste_seed_idempotent_et_rls_isole():
    with _connexion_jetable() as connexion:
        with connexion.cursor() as cur:
            cur.execute("""
                create table public.restaurants (
                    id integer generated by default as identity primary key,
                    name text not null,
                    slug text not null unique
                );
                create table public.restaurant_menus (
                    id integer generated by default as identity primary key,
                    restaurant_id integer not null references public.restaurants(id) on delete cascade,
                    name text not null
                );
                create table public.restaurant_reviews (
                    id integer generated by default as identity primary key,
                    restaurant_id integer not null references public.restaurants(id) on delete cascade,
                    comment text
                );
                insert into public.restaurants (name, slug)
                values ('Restaurant historique', 'historique');
                insert into public.restaurant_menus (restaurant_id, name)
                values (1, 'Menu historique');
                insert into public.restaurant_reviews (restaurant_id, comment)
                values (1, 'Avis historique');

                create schema catalogue;
                create table catalogue.restaurants (
                    id uuid primary key default gen_random_uuid(),
                    slug text not null unique,
                    name text not null,
                    is_published boolean not null default false
                );
                create role anon nologin;
                alter table catalogue.restaurants enable row level security;
                create policy catalogue_public_read
                    on catalogue.restaurants for select to anon
                    using (is_published = true);
                grant usage on schema catalogue to anon;
                grant select on catalogue.restaurants to anon;

                insert into catalogue.restaurants (slug, name, is_published)
                values ('bakel-test', 'Restaurant catalogue', true),
                       ('interne-test', 'Fiche non publiée', false);
            """)

            # Rejouer le même seed par slug met à jour la fiche, sans doublon.
            seed = """
                insert into catalogue.restaurants (slug, name, is_published)
                values ('bakel-test', 'Restaurant catalogue actualisé', true)
                on conflict (slug) do update
                  set name = excluded.name, is_published = excluded.is_published;
            """
            cur.execute(seed)
            cur.execute(seed)

            cur.execute("""
                select count(*), count(distinct slug),
                       (select name from catalogue.restaurants where slug = 'bakel-test')
                from catalogue.restaurants
            """)
            assert cur.fetchone() == (2, 2, "Restaurant catalogue actualisé")

            # La coexistence ne change ni les lignes ni les identifiants historiques.
            cur.execute("""
                select r.id, r.slug, m.id, m.restaurant_id, m.name,
                       v.id, v.restaurant_id, v.comment
                from public.restaurants r
                join public.restaurant_menus m on m.restaurant_id = r.id
                join public.restaurant_reviews v on v.restaurant_id = r.id
            """)
            assert cur.fetchall() == [
                (1, "historique", 1, 1, "Menu historique", 1, 1, "Avis historique")
            ]

            # Le rôle public peut lire uniquement les fiches publiées du nouveau catalogue.
            cur.execute("set role anon")
            cur.execute("select slug from catalogue.restaurants order by slug")
            assert cur.fetchall() == [("bakel-test",)]
            with pytest.raises(Exception):
                cur.execute("select * from public.restaurants")
            cur.execute("reset role")

            cur.execute("""
                select c.relrowsecurity
                from pg_class c
                join pg_namespace n on n.oid = c.relnamespace
                where n.nspname = 'catalogue' and c.relname = 'restaurants'
            """)
            assert cur.fetchone() == (True,)

            # Le POC ne crée aucun objet relationnel supplémentaire dans public.
            cur.execute("""
                select table_name
                from information_schema.tables
                where table_schema = 'public' and table_type = 'BASE TABLE'
                order by table_name
            """)
            assert cur.fetchall() == [
                ("restaurant_menus",),
                ("restaurant_reviews",),
                ("restaurants",),
            ]

            # Les identifiants du catalogue restent UUID ; les identifiants
            # historiques restent integer, sans FK entre les deux modèles.
            cur.execute("""
                select data_type
                from information_schema.columns
                where table_schema = 'catalogue'
                  and table_name = 'restaurants'
                  and column_name = 'id'
            """)
            assert cur.fetchone() == ("uuid",)

            cur.execute("""
                select data_type
                from information_schema.columns
                where table_schema = 'public'
                  and table_name = 'restaurants'
                  and column_name = 'id'
            """)
            assert cur.fetchone() == ("integer",)

            cur.execute("""
                select count(*)
                from pg_constraint fk
                join pg_class source_table on source_table.oid = fk.conrelid
                join pg_namespace source_schema on source_schema.oid = source_table.relnamespace
                join pg_class target_table on target_table.oid = fk.confrelid
                join pg_namespace target_schema on target_schema.oid = target_table.relnamespace
                where fk.contype = 'f'
                  and source_schema.nspname = 'catalogue'
                  and target_schema.nspname = 'public'
            """)
            assert cur.fetchone() == (0,), "Une FK du catalogue pointe vers le modèle historique public."
