"""Tests isolés du précontrôle Supabase : UUID accepté, schéma historique integer bloqué.

Ces tests n'utilisent que des instances PostgreSQL jetables, jamais le projet distant.
La fixture legacy reflète les colonnes/contraintes observées sur Supabase le 2026-10-14.
"""
from __future__ import annotations

import pathlib
import tempfile

import pytest

RACINE = pathlib.Path(__file__).resolve().parents[2]
PREFLIGHT = RACINE / "supabase/diagnostics/preflight_migrations_0001_0007.sql"
SCHEMA = RACINE / "supabase/schema.sql"


def _connexion_jetable():
    pgserver = pytest.importorskip("pgserver")
    psycopg = pytest.importorskip("psycopg")
    serveur = pgserver.get_server(tempfile.mkdtemp(prefix="dekk-preflight-test-"))
    connexion = psycopg.connect(serveur.get_uri(), autocommit=True)
    return connexion


def test_preflight_accepte_schema_de_reference_uuid():
    with _connexion_jetable() as connexion:
        with connexion.cursor() as cur:
            cur.execute(SCHEMA.read_text(encoding="utf-8"))
            cur.execute(PREFLIGHT.read_text(encoding="utf-8"))
            cur.execute("select count(*) from public.restaurants")
            assert cur.fetchone()[0] == 0


def test_preflight_bloque_schema_historique_integer_sans_le_modifier():
    with _connexion_jetable() as connexion:
        with connexion.cursor() as cur:
            # Fixture conforme aux types/contraintes observés dans les tables distantes.
            cur.execute("""
                create table public.restaurants (
                    id integer generated by default as identity primary key,
                    name text not null,
                    slug text not null unique,
                    description text,
                    logo text,
                    cover_photo text,
                    gallery text[],
                    cuisine_types text[],
                    categories text[],
                    price_range text,
                    phone text,
                    whatsapp text,
                    website text,
                    instagram text,
                    facebook text,
                    address text,
                    neighborhood text,
                    city text default 'Dakar',
                    latitude numeric,
                    longitude numeric,
                    opening_hours jsonb,
                    services text[],
                    rating numeric default 4.0,
                    review_count integer default 0,
                    criteria_ratings jsonb,
                    promotions jsonb,
                    reservation_enabled boolean default false,
                    delivery_enabled boolean default false,
                    verified boolean default true,
                    claimed boolean default false,
                    last_verified_at timestamp default current_timestamp
                );
                create table public.restaurant_menus (
                    id integer generated by default as identity primary key,
                    restaurant_id integer references public.restaurants(id) on delete cascade,
                    category text not null,
                    name text not null,
                    description text,
                    price integer not null,
                    image_url text,
                    is_available boolean default true,
                    is_specialty boolean default false
                );
                create table public.restaurant_reviews (
                    id integer generated by default as identity primary key,
                    restaurant_id integer references public.restaurants(id) on delete cascade,
                    author_name text not null,
                    rating integer check (rating >= 1 and rating <= 5),
                    comment text,
                    created_at timestamp default current_timestamp
                );
                insert into public.restaurants (name, slug, neighborhood)
                values ('Restaurant historique test', 'restaurant-historique-test', 'Bakel');
                insert into public.restaurant_menus (restaurant_id, category, name, price)
                values
                  (1, 'plat', 'Menu historique 1', 1000),
                  (1, 'plat', 'Menu historique 2', 1200),
                  (1, 'plat', 'Menu historique 3', 1500),
                  (1, 'boisson', 'Menu historique 4', 500),
                  (1, 'boisson', 'Menu historique 5', 600),
                  (1, 'dessert', 'Menu historique 6', 700);
                insert into public.restaurant_reviews (restaurant_id, author_name, rating, comment)
                values (1, 'Test historique', 5, 'Avis à préserver');
            """)
            with pytest.raises(Exception, match="attendent uuid"):
                cur.execute(PREFLIGHT.read_text(encoding="utf-8"))

            # Le précontrôle doit échouer avant toute modification des données.
            cur.execute("""
                select
                    (select count(*) from public.restaurants),
                    (select count(*) from public.restaurant_menus),
                    (select count(*) from public.restaurant_reviews),
                    (select id from public.restaurants limit 1),
                    (select restaurant_id from public.restaurant_menus limit 1),
                    (select restaurant_id from public.restaurant_reviews limit 1)
            """)
            assert cur.fetchone() == (1, 6, 1, 1, 1, 1)
